export function adminMembershipPermissionPresentation(code) {
  const key = String(code);
  const prefix = key.split(":")[0];
  return Object.freeze({
    label: Object.hasOwn(LABELS, key) ? LABELS[key] : key,
    group: Object.hasOwn(GROUPS, prefix) ? GROUPS[prefix] : "Otros permisos",
  });
}
